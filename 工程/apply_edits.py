def regenerate_chapter_files():
    full_text = TXT_DRAFT.read_text(encoding="utf-8")
    book_names = ["一", "二", "三", "四", "五", "六", "七", "八", "九", "十", "十一", "十二"]

    # Extract each book content from full text
    book_positions = []
    for b_name in book_names:
        header = f"第{b_name}卷\n------------------------------------------------------------------------\n"
        pos = full_text.find(header)
        assert pos != -1, f"Book {b_name} header not found"
        book_positions.append(pos)
    book_positions.append(len(full_text))

    for idx, b_name in enumerate(book_names):
        start = book_positions[idx]
        end = book_positions[idx + 1]
        book_body = full_text[start:end].rstrip() + "\n"

        chapter_path = CHAPTERS_DIR / f"埃涅阿斯纪_第{b_name}卷_附注释.txt"
        old_content = chapter_path.read_text(encoding="utf-8")

        # Keep original 3-line metadata header
        header_lines = old_content.splitlines()[:3]
        new_content = "\n".join(header_lines) + "\n\n" + book_body

        chapter_path.write_text(new_content, encoding="utf-8")
    print("Regenerated all 12 chapter files in 当前分卷_20261006.")


